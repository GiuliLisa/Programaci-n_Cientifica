# Tkinter
# Ventajas:
#     Viene incluido con Python, no necesita instalación extra.
#     Muy ligero y rápido para cosas simples.
#     Bueno para proyectos pequeños o educativos.
#     Fácil de aprender para principiantes.
# Desventajas:
#     Interfaces gráficas limitadas, con aspecto poco moderno.
#     No tan flexible para diseños complejos.
#     No tiene un diseñador visual integrado (todo es manual por código).

# PyQt / Qt Designer
# Ventajas:
#     Interfaz moderna, profesional y con muchos widgets avanzados.
#     Permite usar Qt Designer, un editor visual para diseñar la interfaz sin escribir código.
#     Muy buena documentación y soporte de la comunidad.
#     Ideal para aplicaciones grandes o de calidad profesional.
# Desventajas:
#     Necesita instalación adicional (pyqt5, pyqt-tools, etc.).
#     Puede ser más complejo para principiantes.
#     Algunos componentes (como Qt Designer) pueden requerir configuraciones manuales si se instala por partes.